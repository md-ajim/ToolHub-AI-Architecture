import os

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
APPS_DIR = os.path.join(BASE_DIR, 'apps')

REQUIRED_FILES = [
    '__init__.py',
    'admin.py',
    'apps.py',
    'models.py',
    'selectors.py',
    'services.py',
    'signals.py',
    'tasks.py',
    'urls.py',
    'validators.py',
    'views.py'
]

def ensure_app_structure():
    if not os.path.exists(APPS_DIR):
        print(f"Apps directory not found: {APPS_DIR}")
        return

    for app_name in os.listdir(APPS_DIR):
        app_path = os.path.join(APPS_DIR, app_name)
        if os.path.isdir(app_path) and app_name != '__pycache__':
            print(f"Checking app: {app_name}")
            for filename in REQUIRED_FILES:
                filepath = os.path.join(app_path, filename)
                if not os.path.exists(filepath):
                    with open(filepath, 'w') as f:
                        if filename == 'urls.py':
                            f.write('from django.urls import path\n\nurlpatterns = [\n]\n')
                        elif filename == 'apps.py':
                            camel_case = ''.join(word.title() for word in app_name.split('_'))
                            f.write(f'from django.apps import AppConfig\n\nclass {camel_case}Config(AppConfig):\n    default_auto_field = "django.db.models.BigAutoField"\n    name = "apps.{app_name}"\n')
                        else:
                            f.write('# Generated by structure setup\n')
                    print(f"  Created missing file: {filename}")

if __name__ == "__main__":
    ensure_app_structure()
    print("Backend architecture structure complete.")
